"""Generate a Lakeflow lookup from the versioned, evidence-based store map."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
config = json.loads((ROOT/'config/store_financial_profiles.json').read_text(encoding='utf-8'))
rows = []
for row in config['stores']:
    assert row['financial_profile'] in ('A_TAX_INCLUSIVE', 'B_PRE_DISCOUNT')
    rows.append(f"({int(row['store_id'])}, false, DATE '{row['valid_from']}', DATE '{row['valid_to']}', '{row['financial_profile']}', '{config['version']}')")
# Synthetic populations use the same effective-date scope, never the real store IDs.
for store, profile in [(1, 'A_TAX_INCLUSIVE'), (2, 'B_PRE_DISCOUNT')]:
    rows.append(f"({store}, true, DATE '2025-12-31', DATE '2026-01-01', '{profile}', '{config['version']}')")
source = '''"""Generated by scripts/build_financial_profiles.py; edit config, not this file."""
from pyspark import pipelines as dp

@dp.materialized_view(name='silver_store_financial_profiles')
def store_profiles():
    return spark.sql("""SELECT * FROM VALUES
'''+',\n'.join('      '+r for r in rows)+'''
      AS profiles(store_id, is_demo, valid_from, valid_to, financial_profile, rule_version)
    """)
'''
path = ROOT/'src/transformations/silver/mv_store_financial_profiles.py'
path.write_text(source, encoding='utf-8')
print(path)
